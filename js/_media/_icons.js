// Значки для медиа-нод.
//
// ⚠️ РИСОВАННЫЕ, А НЕ СИМВОЛЫ ШРИФТА. Юникодные глифы («⟲», «⤢», «⦿») выглядят
// по-разному в разных шрифтах, а главное — путаются между собой: «сбросить
// подрезку» читалось как «зациклить», «вписать ролик» — как «на весь экран», а
// «〜» вообще не говорил про звук. Здесь у каждого действия свой силуэт:
// у звука — столбики волны, у подрезки — квадратные скобки, у масштаба — лупа,
// у полного экрана — уголки.
//
// Цвет берётся из currentColor, поэтому значки следуют теме сами.

// ⚠️ Заливка задаётся КЛАССОМ, а не атрибутом. Атрибут fill — это представление,
// и любое чужое правило для svg внутри кнопки его перебивает: круг лупы и рамка
// окна выходили сплошными пятнами. Правила лежат в стиле видео-нод.
const SVG = (body, extra = "") =>
    `<svg viewBox="0 0 16 16" width="14" height="14" `
    + `stroke="currentColor" stroke-width="1.6" stroke-linecap="round" `
    + `stroke-linejoin="round" aria-hidden="true"${extra}>${body}</svg>`;

const ICONS = {
    // Треугольник — заливкой: контурный «play» на мелком размере читается хуже.
    play: SVG('<path d="M5 3.2 12.4 8 5 12.8Z" class="ts-ico-solid" stroke-width="1.2"/>'),
    pause: SVG('<path d="M5.6 3.4v9.2M10.4 3.4v9.2" stroke-width="2"/>'),

    // Замкнутая петля со стрелкой — только у повтора.
    loop: SVG('<path d="M3.4 6.6A3.2 3.2 0 0 1 6.6 3.4h5.2"/>'
              + '<path d="M10 1.6l2 1.8-2 1.8"/>'
              + '<path d="M12.6 9.4a3.2 3.2 0 0 1-3.2 3.2H4.2"/>'
              + '<path d="M6 14.4l-2-1.8 2-1.8"/>'),

    sound: SVG('<path d="M3 6.2v3.6h2.4L8.6 12.6V3.4L5.4 6.2Z" class="ts-ico-solid" '
               + 'stroke-width="1.2"/><path d="M11 6.1a2.6 2.6 0 0 1 0 3.8"/>'
               + '<path d="M12.8 4.3a5 5 0 0 1 0 7.4"/>'),
    muted: SVG('<path d="M3 6.2v3.6h2.4L8.6 12.6V3.4L5.4 6.2Z" class="ts-ico-solid" '
               + 'stroke-width="1.2"/><path d="M11.2 6.4l3.2 3.2M14.4 6.4l-3.2 3.2"/>'),

    // Звуковая дорожка — столбики разной высоты, ни с чем не спутаешь.
    wave: SVG('<path d="M2.2 7v2M4.6 5.2v5.6M7 2.6v10.8M9.4 4.4v7.2M11.8 6v4M14.2 7.2v1.6"/>'),

    // Сбросить подрезку: скобки разъезжаются к самым краям ролика.
    resetTrim: SVG('<path d="M2.4 3v10M13.6 3v10"/>'
                   + '<path d="M6.4 8h-3M4.6 6.4 3 8l1.6 1.6"/>'
                   + '<path d="M9.6 8h3M11.4 6.4 13 8l-1.6 1.6"/>'),

    // Вписать ролик: рамка окна и стрелка во всю его ширину.
    fit: SVG('<rect x="1.8" y="4" width="12.4" height="8" rx="1.6"/>'
             + '<path d="M4.4 8h7.2"/><path d="M6 6.6 4.4 8 6 9.4"/>'
             + '<path d="M10 6.6 11.6 8 10 9.4"/>'),

    // ⚠️ Внутри лупы на 14 пикселях плюс и минус не читаются — проверено на
    // снимке: три значка выглядели одинаково. Поэтому знак вынесен НАРУЖУ, а у
    // «приблизить к выделению» вообще другой силуэт: скобки выделения со
    // стрелками внутрь.
    zoomIn: SVG('<circle cx="6.6" cy="6.6" r="4.2"/><path d="M9.8 9.8 14 14"/>'
                + '<path d="M6.6 4.8v3.6M4.8 6.6h3.6"/>'),
    zoomOut: SVG('<circle cx="6.6" cy="6.6" r="4.2"/><path d="M9.8 9.8 14 14"/>'
                 + '<path d="M4.8 6.6h3.6"/>'),
    zoomSelection: SVG('<path d="M3 2.6v10.8M13 2.6v10.8"/>'
                       + '<path d="M5.4 8h2.2M6.6 6.4 8.2 8l-1.6 1.6"/>'
                       + '<path d="M10.6 8H8.4M9.4 6.4 7.8 8l1.6 1.6"/>'),

    // Полный экран — четыре уголка, и больше нигде их нет.
    fullscreen: SVG('<path d="M2.6 6V2.6H6"/><path d="M10 2.6h3.4V6"/>'
                    + '<path d="M13.4 10v3.4H10"/><path d="M6 13.4H2.6V10"/>'),
};

/**
 * Значок по имени.
 *
 * @param {keyof ICONS} name
 * @returns {string} разметка SVG
 */
export function icon(name) {
    return ICONS[name] || "";
}

/** Поставить значок в уже существующую кнопку. */
export function setIcon(element, name) {
    if (element) element.innerHTML = icon(name);
}

"""Кривые переноса HDR-ветки: ACEScct и обратная sRGB.

ACEScct — кривая, в которой LTX 2.5 видит HDR.

VAE принимает картинку в ``[0, 1]``. Сцена в EXR так не живёт: солнце в кадре
бывает в сотни раз ярче белой бумаги. ACEScct — логарифмическая кривая, которая
укладывает этот разлёт в единичный отрезок так, что равные шаги по коду дают
равные шаги по стопам экспозиции. Именно её использует нативный HDR-путь
LTX 2.5, поэтому и мы кодируем ею — иначе модель увидит не то распределение
яркостей, на котором её учили.

Формулы взяты из опубликованной спецификации ACEScct (docs.acescentral.com), а
не из исходников Lightricks — так пакет остаётся независимой реализацией.

⚠️ **Рабочий сигнал зажат в ``[0, 1]``, и это не наша самодеятельность, а
контракт модели.** Верхняя единица кода соответствует линейной яркости
``2**(17.52 - 9.72) = 2**7.8 ≈ 222.86``. Всё, что в исходном EXR ярче, на входе
в модель сплющивается в единицу. Это 7.8 стопа над белым и примерно 10.6 стопа
над средне-серым 0.18 — для съёмочного материала с запасом, для синтетической
сцены с источником света в кадре может и не хватить. Нода статистики про это
предупреждает.

⚠️ Обратное преобразование зажимается **только снизу**. Верхнюю границу не
трогаем никогда: ровно там и живёт HDR, ради которого всё затевалось.

Модуль намеренно не знает ни про ComfyUI, ни про ноды — только torch.
"""

from __future__ import annotations

import torch

# Константы спецификации ACEScct.
_A = 10.5402377416545          # наклон линейного участка
_B = 0.0729055341958355        # его сдвиг
_X_BRK = 0.0078125             # 2**-7, стык линейного и логарифмического участков
_Y_BRK = 0.155251141552511     # тот же стык со стороны кода

# log2 самого маленького числа, которое ещё имеет смысл логарифмировать.
_TINY = 1e-12

# Линейная яркость, которой соответствует код 1.0. Держим отдельно, чтобы
# статистика могла честно сказать, сколько именно обрежется.
WORKING_CEILING = float(2.0 ** (17.52 - 9.72))


def linear_ap1_to_acescct(x: torch.Tensor) -> torch.Tensor:
    """Линейный AP1 → рабочий сигнал ACEScct в ``[0, 1]``.

    Args:
        x: тензор любой формы, линейные значения в примариях AP1 (ACEScg).

    Returns:
        Тензор той же формы, float32, значения в ``[0, 1]``.
    """
    value = x.to(torch.float32).clamp_min(0.0)
    log_part = (torch.log2(value.clamp_min(_TINY)) + 9.72) / 17.52
    lin_part = _A * value + _B
    working = torch.where(value > _X_BRK, log_part, lin_part)
    return working.clamp(0.0, 1.0)


def srgb_to_linear(x: torch.Tensor) -> torch.Tensor:
    """Обычная картинка (JPG/PNG) → линейный свет в примариях Rec.709.

    Обратная кривая sRGB по IEC 61966-2-1. Нужна там, где в HDR-ветку подают не
    EXR, а обычное изображение: оно закодировано ГАММОЙ, и если принять его коды
    за линейный свет, тона уедут. Замерено: расхождение кода ACEScct доходит до
    **0.131** — около 2.3 стопа в полутонах.

    ⚠️ Диапазона это не добавляет. Белый 1.0 в JPG остаётся линейной единицей, то
    есть кодом ACEScct 0.555; выше — пусто. Никакая кривая не восстановит то,
    чего в файле нет.
    """
    value = x.to(torch.float32)
    low = value / 12.92
    high = torch.pow((value.clamp_min(0.0) + 0.055) / 1.055, 2.4)
    return torch.where(value <= 0.04045, low, high)


def acescct_to_linear_ap1(ct: torch.Tensor) -> torch.Tensor:
    """Рабочий сигнал ACEScct → линейный AP1.

    Зажимает результат снизу нулём: код ``0.0`` формально отображается в
    ``-0.0069``, а отрицательной яркости не бывает. Сверху не зажимает.

    Args:
        ct: тензор любой формы, коды ACEScct.

    Returns:
        Тензор той же формы, float32, линейные значения ``>= 0``.
    """
    code = ct.to(torch.float32).clamp(0.0, 1.0)
    log_part = torch.pow(torch.tensor(2.0, dtype=torch.float32, device=code.device),
                         code * 17.52 - 9.72)
    lin_part = (code - _B) / _A
    linear = torch.where(code > _Y_BRK, log_part, lin_part)
    return linear.clamp_min(0.0)

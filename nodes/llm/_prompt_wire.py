"""Вход `prompt` у TS Super Prompt и TS Super Prompt RT — общее правило.

Обе ноды принимают промпт с провода отдельным необязательным гнездом `prompt`,
а не превращают в гнездо своё текстовое поле: редактор ноды это поле прячет
(в Nodes 2.0 иначе ломается раскладка), и подключённое поле показывало бы в
редакторе текст, который запуск уже не читает.

Правило одно на обе ноды, чтобы они не разошлись:

* провод подключён и принёс непустой текст — работает он, поле не читается;
* пришла пустая строка (или провода нет) — работает поле, как раньше;
* текст с провода по умолчанию уходит КАК ЕСТЬ; улучшается при запуске,
  только если включён `enhance_prompt` (просьба владельца: подключение провода
  само по себе не должно запускать модель).

Результат запуска с провода нода отдаёт в интерфейс под ключом
``RESULT_UI_KEY`` и показывает под полем — В САМО ПОЛЕ его не пишут:
изменённый виджет сбил бы кэш ComfyUI, и следующий запуск пересчитал бы всё
ниже по графу, включая сэмплер.
"""

from __future__ import annotations

# Ключ ui-выхода; его же читает `js/llm/_prompt_wire.js`.
RESULT_UI_KEY = "ts_super_prompt_result"


def wired_prompt(value) -> str:
    """Текст с провода, если он есть и не пустой; иначе пустая строка.

    Сам текст не обрезается — пробелы и переводы строк внутри промпта
    принадлежат автору; пустота определяется без них.
    """
    if value is None or isinstance(value, bool):
        return ""
    if isinstance(value, (list, tuple)):
        # Списковый выход выше по графу: берём первый непустой, как сделал бы
        # человек, подключивший одну строку.
        return next((wired_prompt(item) for item in value if wired_prompt(item)), "")
    text = str(value)
    return text if text.strip() else ""
